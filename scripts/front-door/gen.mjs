#!/usr/bin/env node
// FRONT-DOOR-timeway (t_52034498): builds apps/web/modules/marketing/front-door.generated.ts from
//   - docs/launch/timeway.yaml (front-door copy, EN+AR; same schema as salesos packages/site-kit/src/launch-content.ts)
//   - awasfie/passport docs/billing/price-map.md (PART CM, tax inclusive): the only source of a Timeway amount.
// The page code never types a number that is a price; plans.ts reads the generated table.
//
//   node scripts/front-door/gen.mjs --price-map <passport>/docs/billing/price-map.md [--passport-sha <sha>]
//   node scripts/front-door/gen.mjs --price-map <path> --check     exit 1 if the committed file differs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = join(root, "apps/web/modules/marketing/front-door.generated.ts");
const YAML = join(root, "docs/launch/timeway.yaml");
const KEYS = [
  "timeway_pro_monthly",
  "timeway_pro_yearly",
  "timeway_teams_monthly",
  "timeway_teams_yearly",
  "timeway_business_monthly",
  "timeway_business_yearly",
];
const BANNED = /^(price|prices|amount|cost|currency)$/i;

const arg = (n) => {
  const i = process.argv.indexOf(n);
  return i > 0 ? process.argv[i + 1] : undefined;
};

/** The "## Prices" table rows: | `key` | `price_id` | `amount` | `interval` | `type` | trial | `tax` | active | */
export function parsePriceMap(md) {
  const rows = {};
  const start = md.search(/^## Prices/m);
  if (start < 0) throw new Error("price-map.md: no '## Prices' section");
  const body = md.slice(start).split(/\n## /)[0];
  for (const line of body.split("\n")) {
    const c = line.split("|").map((s) => s.trim().replace(/^`|`$/g, ""));
    if (c.length < 9 || !/^[a-z0-9_]+$/.test(c[1] ?? "") || !c[2].startsWith("price_")) continue;
    const amount = /^\d+$/.test(c[3]) ? Number(c[3]) : null;
    rows[c[1]] = {
      priceId: c[2],
      amountMinor: amount,
      interval: c[4],
      type: c[5],
      trialDays: /^\d+$/.test(c[6]) ? Number(c[6]) : null,
      tax: c[7],
      active: c[8] === "True",
    };
  }
  return rows;
}

function l10n(v, path) {
  const out = {};
  for (const l of ["en", "ar"]) {
    if (typeof v?.[l] !== "string" || !v[l].trim()) throw new Error(`${path}.${l}: missing or empty`);
    out[l] = v[l].trim();
  }
  return out;
}

function noPrices(v, path) {
  if (Array.isArray(v)) v.forEach((x, i) => noPrices(x, `${path}[${i}]`));
  else if (v && typeof v === "object")
    for (const [k, x] of Object.entries(v)) {
      if (BANNED.test(k))
        throw new Error(`${path}.${k}: launch content must not carry prices (PART CM only)`);
      noPrices(x, `${path}.${k}`);
    }
}

export function parseLaunch(text) {
  const doc = yaml.load(text);
  noPrices(doc, "timeway.yaml");
  const h = doc?.home;
  if (!h?.hero) throw new Error("timeway.yaml: missing home.hero");
  if (!Array.isArray(h.features) || h.features.length < 1 || h.features.length > 6)
    throw new Error("timeway.yaml: home.features needs 1..6 items");
  return {
    hero: {
      title: l10n(h.hero.title, "home.hero.title"),
      sub: l10n(h.hero.sub, "home.hero.sub"),
      cta: l10n(h.hero.cta, "home.hero.cta"),
    },
    features: h.features.map((f, i) => ({
      title: l10n(f.title, `home.features[${i}].title`),
      body: l10n(f.body, `home.features[${i}].body`),
    })),
  };
}

/** Biome-formatted TS literal: bare identifier keys, trailing commas, 2-space indent. */
function lit(v, ind = "") {
  const next = `${ind}  `;
  if (Array.isArray(v)) return `[\n${v.map((x) => `${next}${lit(x, next)},\n`).join("")}${ind}]`;
  if (v && typeof v === "object") {
    const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
    return `{\n${Object.entries(v)
      .map(([k, x]) => `${next}${key(k)}: ${lit(x, next)},\n`)
      .join("")}${ind}}`;
  }
  return JSON.stringify(v);
}

export function build(priceMapText, yamlText) {
  const rows = parsePriceMap(priceMapText);
  const prices = {};
  for (const k of KEYS) {
    const r = rows[k];
    if (!r) throw new Error(`price-map.md: ${k} missing`);
    if (r.tax !== "inclusive") throw new Error(`price-map.md: ${k} is not tax inclusive`);
    if (!r.active || r.type !== "licensed" || r.amountMinor === null)
      throw new Error(`price-map.md: ${k} unusable`);
    prices[k] = { amountMinor: r.amountMinor, currency: "USD", interval: r.interval, trialDays: r.trialDays };
  }
  const sha = createHash("sha256").update(priceMapText).digest("hex");
  const launch = parseLaunch(yamlText);
  return (
    "// GENERATED by scripts/front-door/gen.mjs (t_52034498). Do not edit: change docs/launch/timeway.yaml or\n" +
    "// passport docs/billing/price-map.md (PART CM) and re-run the generator.\n" +
    `export const PRICE_MAP_SHA256 = ${JSON.stringify(sha)};\n` +
    `export const TIMEWAY_PRICES = ${lit(prices)} as const;\n` +
    `export const LAUNCH = ${lit(launch)} as const;\n`
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const pm = arg("--price-map");
  if (!pm) {
    console.error("usage: gen.mjs --price-map <passport>/docs/billing/price-map.md [--check]");
    process.exit(2);
  }
  const out = build(readFileSync(pm, "utf8"), readFileSync(YAML, "utf8"));
  if (process.argv.includes("--check")) {
    if (readFileSync(OUT, "utf8") !== out) {
      console.error("front-door.generated.ts is out of date: run scripts/front-door/gen.mjs");
      process.exit(1);
    }
    console.log("front door in sync with price-map.md and timeway.yaml");
  } else {
    writeFileSync(OUT, out);
    console.log(`wrote ${OUT}`);
  }
}
