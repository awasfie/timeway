import { afterAll, beforeAll, it } from "vitest";
import { seedCc13Tenants, type Cc13Seed } from "./seed";
import { attempt, prisma, viewerFor } from "./trpc-harness";
let seed: Cc13Seed;
beforeAll(async () => { seed = await seedCc13Tenants(); });
afterAll(async () => { await seed?.cleanup(); });
const p = (n: string, o: unknown) => process.stderr.write(`DIAG ${n}: ${JSON.stringify(o)?.slice(0, 300)}\n`);
it("diag", async () => {
  const { A, B } = seed; const v = await viewerFor(B.owner.id);
  const start = new Date(Date.UTC(2031, 1, 1, 9));
  const bk = await prisma.booking.create({ data: { uid: `cc13-${seed.runId}-a-p1`, title: "p", startTime: start, endTime: new Date(start.getTime()+1800000), user: { connect: { id: A.owner.id } }, eventType: { connect: { id: A.eventType.id } }, status: "PENDING", twOrgId: A.twOrg.id }, select: { id: true } });
  p("confirm", await attempt(() => v.bookings.confirm({ bookingId: bk.id, confirmed: true } as never)));
  p("status", await prisma.booking.findUnique({ where: { id: bk.id }, select: { status: true } }));
  const c = await prisma.credential.create({ data: { type: "cc13_probe", key: {}, userId: A.owner.id, teamId: A.team.id, twOrgId: A.twOrg.id }, select: { id: true } });
  p("creddel", await attempt(() => v.credentials.delete({ id: c.id })));
  p("cred after", await prisma.credential.findUnique({ where: { id: c.id }, select: { id: true } }));
  p("creddel team", await attempt(() => v.credentials.delete({ id: c.id, teamId: A.team.id })));
  p("cred after2", await prisma.credential.findUnique({ where: { id: c.id }, select: { id: true } }));
  const n0 = await prisma.schedule.count({ where: { OR: [{ userId: B.owner.id }, { userId: A.owner.id }] } });
  p("dup", await attempt(() => v.availability.schedule.duplicate({ scheduleId: A.schedule.id } as never)));
  p("dup counts", [n0, await prisma.schedule.count({ where: { OR: [{ userId: B.owner.id }, { userId: A.owner.id }] } })]);
  await prisma.credential.deleteMany({ where: { id: c.id } });
});
