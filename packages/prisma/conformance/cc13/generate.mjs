#!/usr/bin/env node
/**
 * CC-13 (extended) — tenant-scoped model list, generated from schema.prisma (WC-TW-7a).
 *
 * A "tenant model" is any model with a scalar field named organizationId, teamId,
 * orgId or twOrgId, plus the tenant roots Team (upstream) and Organization (Timeway). The schema is read
 * through getDMMF so comments, @@map and multi-line attributes cannot fool it.
 *
 *   node packages/prisma/conformance/cc13/generate.mjs           # rewrite models.generated.json
 *   node packages/prisma/conformance/cc13/generate.mjs --check   # exit 1 when the committed file is stale
 *
 * coverage.test.ts runs the same check in the unit suite, so a schema change that adds
 * a tenant model fails CI until the JSON is regenerated and manifest.ts covers it.
 */
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

export const TENANT_FIELDS = ["organizationId", "teamId", "orgId", "twOrgId"];
// Team is the upstream tenant root; Organization (tw_organization) is the Timeway one: their own id is the tenant key.
export const TENANT_ROOTS = ["Organization", "Team"];

const here = path.dirname(fileURLToPath(import.meta.url));
export const SCHEMA_PATH = path.resolve(here, "../../schema.prisma");
export const GENERATED_PATH = path.join(here, "models.generated.json");

const require = createRequire(import.meta.url);

export async function buildTenantModels(schemaPath = SCHEMA_PATH) {
  const { getDMMF } = require("@prisma/internals");
  const dmmf = await getDMMF({ datamodel: fs.readFileSync(schemaPath, "utf8") });
  const models = [];
  for (const m of dmmf.datamodel.models) {
    const fields = m.fields
      .filter((f) => f.kind === "scalar" && TENANT_FIELDS.includes(f.name))
      .map((f) => ({ name: f.name, type: f.type, nullable: !f.isRequired }));
    const isRoot = TENANT_ROOTS.includes(m.name);
    if (!fields.length && !isRoot) continue;
    models.push({
      model: m.name,
      table: m.dbName ?? m.name,
      root: isRoot,
      tenantFields: fields,
      nullable: fields.length > 0 && fields.every((f) => f.nullable),
    });
  }
  // Code-point order, not localeCompare: the file must be byte-identical on every machine.
  models.sort((a, b) => (a.model < b.model ? -1 : a.model > b.model ? 1 : 0));
  return {
    note: "GENERATED by packages/prisma/conformance/cc13/generate.mjs from schema.prisma. Do not edit.",
    rule: { tenantFields: TENANT_FIELDS, roots: TENANT_ROOTS },
    count: models.length,
    models,
  };
}

export const serialize = (doc) => `${JSON.stringify(doc, null, 2)}\n`;

/** True when two JSON texts hold the same document, whatever their whitespace. */
export const isSameDoc = (a, b) => JSON.stringify(JSON.parse(a)) === JSON.stringify(JSON.parse(b));

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const next = serialize(await buildTenantModels());
  if (process.argv.includes("--check")) {
    // Compare content, not bytes: Biome may reformat the committed JSON.
    const current = fs.existsSync(GENERATED_PATH) ? fs.readFileSync(GENERATED_PATH, "utf8") : "null";
    if (!isSameDoc(current, next)) {
      console.error(
        "CC-13: models.generated.json is stale; run node packages/prisma/conformance/cc13/generate.mjs"
      );
      process.exit(1);
    }
    console.log("CC-13: models.generated.json is current");
  } else {
    fs.writeFileSync(GENERATED_PATH, next);
    console.log(
      `CC-13: wrote ${path.relative(process.cwd(), GENERATED_PATH)} (${JSON.parse(next).count} models)`
    );
  }
}
